"""Write model.npz to weights.h and put one test image per digit in samples/."""
import os

import numpy as np

import mnist

HERE = os.path.dirname(os.path.abspath(__file__))


def c_values(a, indent):
    # %.9g round-trips every float32 exactly.
    vals = [f"{v:.9g}f" for v in a.tolist()]
    lines = [", ".join(vals[i:i + 8]) for i in range(0, len(vals), 8)]
    return indent + (",\n" + indent).join(lines)


def c_array(name, a):
    dims = "".join(f"[{d}]" for d in a.shape)
    if a.ndim == 1:
        body = c_values(a, "    ")
    else:
        body = ",\n".join("    {\n" + c_values(row, "        ") + "\n    }" for row in a)
    return f"static const float {name}{dims} = {{\n{body}\n}};\n"


def header(params):
    w1, w2 = params["W1"], params["W2"]
    out = [
        "/* Generated by export.py from model.npz. Do not edit. */\n",
        "#ifndef WEIGHTS_H\n#define WEIGHTS_H\n\n",
        f"#define N_IN {w1.shape[1]}\n#define N_HIDDEN {w1.shape[0]}\n#define N_OUT {w2.shape[0]}\n\n",
    ]
    for name in ("W1", "b1", "W2", "b2"):
        out.append(c_array(name, params[name].astype(np.float32)))
    out.append("\n#endif\n")
    return "".join(out)


def write_pgm(path, pixels):
    with open(path, "wb") as f:
        f.write(b"P5\n28 28\n255\n" + pixels.astype(np.uint8).tobytes())


def main():
    params = dict(np.load(os.path.join(HERE, "model.npz")))
    with open(os.path.join(HERE, "weights.h"), "w") as f:
        f.write(header(params))
    print("wrote weights.h")

    images, labels = mnist.load("t10k")
    os.makedirs(os.path.join(HERE, "samples"), exist_ok=True)
    for digit in range(10):
        i = int(np.argmax(labels == digit))  # first test image of this digit
        write_pgm(os.path.join(HERE, "samples", f"{digit}.pgm"), images[i])
        print(f"wrote samples/{digit}.pgm (test index {i})")


if __name__ == "__main__":
    main()
